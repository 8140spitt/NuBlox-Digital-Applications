    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_corpdev_valuation_public (public_id),
    UNIQUE KEY uq_corpdev_valuation_version (organisation_id, opportunity_id, valuation_code, version_number),
    KEY idx_corpdev_valuation_opportunity (organisation_id, opportunity_id, lifecycle_status),
    CONSTRAINT fk_corpdev_valuation_org FOREIGN KEY (organisation_id) REFERENCES organisations(id),
    CONSTRAINT fk_corpdev_valuation_opportunity FOREIGN KEY (opportunity_id) REFERENCES corporate_development_opportunities(id),
    CONSTRAINT fk_corpdev_valuation_supersedes FOREIGN KEY (supersedes_valuation_id) REFERENCES corporate_development_valuations(id),
    CONSTRAINT fk_corpdev_valuation_approved_by FOREIGN KEY (approved_by_member_id) REFERENCES organisation_members(id),
    CONSTRAINT fk_corpdev_valuation_created_by FOREIGN KEY (created_by_member_id) REFERENCES organisation_members(id),
    CONSTRAINT chk_corpdev_valuation_method CHECK (primary_method IN ('dcf','precedent_transactions','trading_comparables','asset_based','sum_of_parts','venture_method','other')),
    CONSTRAINT chk_corpdev_valuation_status CHECK (lifecycle_status IN ('draft','approved','superseded','withdrawn')),
    CONSTRAINT chk_corpdev_valuation_ev_range CHECK (enterprise_value_low IS NULL OR enterprise_value_high IS NULL OR enterprise_value_low <= enterprise_value_high),
    CONSTRAINT chk_corpdev_valuation_equity_range CHECK (equity_value_low IS NULL OR equity_value_high IS NULL OR equity_value_low <= equity_value_high)
