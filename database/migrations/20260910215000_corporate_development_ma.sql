CREATE TABLE corporate_development_valuations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    organisation_id BIGINT UNSIGNED NOT NULL,
    opportunity_id BIGINT UNSIGNED NOT NULL,
    valuation_code VARCHAR(50) NOT NULL,
    version_number INT UNSIGNED NOT NULL DEFAULT 1,
    title VARCHAR(255) NOT NULL,
    valuation_date DATE NOT NULL,
    currency_code CHAR(3) NOT NULL,
    primary_method VARCHAR(30) NOT NULL,
    lifecycle_status VARCHAR(20) NOT NULL DEFAULT 'draft',
    enterprise_value_low DECIMAL(20,4) NULL,
    enterprise_value_base DECIMAL(20,4) NULL,
    enterprise_value_high DECIMAL(20,4) NULL,
    equity_value_low DECIMAL(20,4) NULL,
    equity_value_base DECIMAL(20,4) NULL,
    equity_value_high DECIMAL(20,4) NULL,
    recommendation TEXT NOT NULL,
    supersedes_valuation_id BIGINT UNSIGNED NULL,
    approved_by_member_id BIGINT UNSIGNED NULL,
    approved_at TIMESTAMP NULL,
